"""
web_app.py - Web Portal Backend for Self-Healing Spreadsheet to Power BI Engine
Provides REST API endpoints for uploading messy business spreadsheets,
running automated healing & semantic modeling, and serving downloadable Power BI packs.
"""

import os
import io
import uuid
import json
import zipfile
from datetime import datetime, timedelta
import pandas as pd
from flask import Flask, request, jsonify, render_template, send_file

from cleaner import SelfHealingCleaner
from pbi_model import PowerBIModelGenerator

app = Flask(__name__, static_folder="static", template_folder="templates")
app.config["MAX_CONTENT_LENGTH"] = 32 * 1024 * 1024  # 32MB max upload

# In-memory session artifact cache: session_id -> { artifacts, created_at }
SESSIONS = {}

SAMPLE_FILE_PATH = r"D:\Documents\power_bi_test_sample.xlsx"


def prune_old_sessions():
    """Remove sessions older than 2 hours to maintain minimal memory footprint."""
    now = datetime.now()
    expired = [sid for sid, data in SESSIONS.items() if now - data["created_at"] > timedelta(hours=2)]
    for sid in expired:
        SESSIONS.pop(sid, None)


def build_analysis_payload(cleaner: SelfHealingCleaner, df: pd.DataFrame, filename: str) -> dict:
    """Run semantic modeling, compute KPIs/charts, and prepare session artifacts."""
    prune_old_sessions()
    session_id = str(uuid.uuid4())

    # 1. Power BI Model & DAX Generation
    model_gen = PowerBIModelGenerator(df, csv_path="cleaned_sales.csv", table_name="Sales")
    measures = model_gen.generate_dax_measures()
    m_script = model_gen.generate_power_query_m()

    # 2. Markdown Cheatsheet Content
    cheatsheet_lines = [
        f"# Auto-Generated Power BI Measures for `Sales`",
        f"Generated: {datetime.now().strftime('%Y-%m-%d %H:%M:%S')}",
        "",
        "| Measure Name | Format | DAX Expression | Description |",
        "| :--- | :--- | :--- | :--- |",
    ]
    for m in measures:
        dax_escaped = m["dax"].replace("|", "\\|")
        cheatsheet_lines.append(f"| **{m['name']}** | `{m['format']}` | `{dax_escaped}` | {m['description']} |")
    cheatsheet_content = "\n".join(cheatsheet_lines)

    # 3. DAX File Content
    dax_lines = []
    for m in measures:
        dax_lines.append(f"// Measure: {m['name']} ({m['format']})")
        dax_lines.append(f"// {m['description']}")
        dax_lines.append(f"{m['dax']}\n")
    dax_file_content = "\n".join(dax_lines)

    # 4. Cleaned CSV in-memory
    csv_buffer = io.StringIO()
    df.to_csv(csv_buffer, index=False)
    cleaned_csv_str = csv_buffer.getvalue()

    # 5. Readme for the downloaded pack
    readme_content = f"""================================================================================
Power BI Starter Kit - Auto-Generated by AutoBI
Source File: {filename}
Generated: {datetime.now().strftime('%Y-%m-%d %H:%M:%S')}
================================================================================

HOW TO USE IN POWER BI DESKTOP IN 60 SECONDS:

1. IMPORT THE CLEAN DATA:
   - Open Power BI Desktop.
   - Click "Get Data" -> "Text/CSV" -> Select 'cleaned_sales.csv' from this folder.
   - Click "Load".

   (Alternative with Power Query M Script):
   - Click "Transform Data" -> "Home" -> "Advanced Editor".
   - Paste the code from 'LoadData.m' into the editor.
   - Adjust the file path to point to where you saved 'cleaned_sales.csv'.

2. ADD PRODUCTION DAX MEASURES:
   - In Power BI Desktop, select the 'Sales' table.
   - Click "New Measure" on the Modeling ribbon.
   - Open 'dax_measures.dax' or 'POWER_BI_MEASURES_CHEATSHEET.md'.
   - Copy and paste the DAX formulas (e.g. Total Revenue, Average Order Value).

3. CHECK YOUR DATA HEALING LOG:
   - Open 'audit_log.json' to review the human summary rows pruned and formulas inferred.

Enjoy high-fidelity data intelligence!
"""

    # Store in memory for instant download
    SESSIONS[session_id] = {
        "created_at": datetime.now(),
        "cleaned_csv": cleaned_csv_str,
        "dax_content": dax_file_content,
        "m_script": m_script,
        "cheatsheet": cheatsheet_content,
        "audit_log": cleaner.audit_log,
        "readme": readme_content,
        "filename": filename,
    }

    # 6. Aggregate KPIs for Web UI
    cols = list(df.columns)
    total_rev = float(df["total_revenue"].sum()) if "total_revenue" in cols else 0.0
    total_units = int(df["units_sold"].sum()) if "units_sold" in cols else 0
    total_orders = int(df["order_id"].nunique()) if "order_id" in cols else len(df)
    aov = (total_rev / total_orders) if total_orders > 0 else 0.0

    completed_rev = float(df[df["status"] == "Completed"]["total_revenue"].sum()) if "status" in cols and "total_revenue" in cols else 0.0
    cancelled_rev = float(df[df["status"] == "Cancelled"]["total_revenue"].sum()) if "status" in cols and "total_revenue" in cols else 0.0
    pending_rev = float(df[df["status"] == "Pending"]["total_revenue"].sum()) if "status" in cols and "total_revenue" in cols else 0.0

    cancellation_rate = (len(df[df["status"] == "Cancelled"]) / len(df) * 100) if "status" in cols and len(df) > 0 else 0.0
    completion_rate = (len(df[df["status"] == "Completed"]) / len(df) * 100) if "status" in cols and len(df) > 0 else 0.0

    # 7. Chart Aggregations
    cat_chart = {}
    if "category" in cols and "total_revenue" in cols:
        cat_chart = {str(k): round(float(v), 2) for k, v in df.groupby("category")["total_revenue"].sum().items()}

    reg_chart = {}
    if "region" in cols and "total_revenue" in cols:
        reg_chart = {str(k): round(float(v), 2) for k, v in df.groupby("region")["total_revenue"].sum().items()}

    status_chart = {}
    if "status" in cols:
        status_chart = {str(k): int(v) for k, v in df["status"].value_counts().items()}

    # 8. Sample Table Records (up to 50 rows)
    preview_df = df.head(50).copy()
    # Format dates as YYYY-MM-DD
    for c in preview_df.columns:
        if pd.api.types.is_datetime64_any_dtype(preview_df[c]):
            preview_df[c] = preview_df[c].dt.strftime("%Y-%m-%d")

    records = preview_df.fillna("").to_dict(orient="records")

    return {
        "success": True,
        "session_id": session_id,
        "filename": filename,
        "kpis": {
            "total_revenue": total_rev,
            "total_units": total_units,
            "total_orders": total_orders,
            "aov": aov,
            "completed_rev": completed_rev,
            "cancelled_rev": cancelled_rev,
            "pending_rev": pending_rev,
            "cancellation_rate": round(cancellation_rate, 1),
            "completion_rate": round(completion_rate, 1),
        },
        "charts": {
            "category": cat_chart,
            "region": reg_chart,
            "status": status_chart,
        },
        "audit_log": cleaner.audit_log,
        "dax_measures": measures,
        "power_query_m": m_script,
        "table_columns": list(df.columns),
        "table_records": records,
    }


@app.route("/")
def index():
    return render_template("index.html")


@app.route("/api/upload", methods=["POST"])
def upload_file():
    if "file" not in request.files:
        return jsonify({"success": False, "error": "No file uploaded"}), 400

    file = request.files["file"]
    if not file.filename:
        return jsonify({"success": False, "error": "Empty filename"}), 400

    filename = file.filename
    lower_ext = os.path.splitext(filename)[1].lower()
    if lower_ext not in [".xlsx", ".xls", ".csv"]:
        return jsonify({"success": False, "error": f"Unsupported format '{lower_ext}'. Please upload an Excel (.xlsx, .xls) or CSV file."}), 400

    try:
        # Read file buffer directly
        file_bytes = file.read()
        file_buffer = io.BytesIO(file_bytes)

        cleaner = SelfHealingCleaner(file_buffer, filename=filename)
        df_clean = cleaner.clean()
        result = build_analysis_payload(cleaner, df_clean, filename)
        return jsonify(result)
    except Exception as e:
        return jsonify({"success": False, "error": str(e)}), 500


@app.route("/api/sample", methods=["POST"])
def run_sample():
    if not os.path.exists(SAMPLE_FILE_PATH):
        return jsonify({"success": False, "error": f"Sample file not found at {SAMPLE_FILE_PATH}"}), 404

    try:
        cleaner = SelfHealingCleaner(SAMPLE_FILE_PATH)
        df_clean = cleaner.clean()
        result = build_analysis_payload(cleaner, df_clean, "power_bi_test_sample.xlsx")
        return jsonify(result)
    except Exception as e:
        return jsonify({"success": False, "error": str(e)}), 500


@app.route("/api/download/<session_id>")
def download_pack(session_id: str):
    session = SESSIONS.get(session_id)
    if not session:
        return jsonify({"error": "Session expired or invalid. Please re-run the analysis."}), 404

    # Build ZIP archive in memory
    zip_buffer = io.BytesIO()
    with zipfile.ZipFile(zip_buffer, "w", zipfile.ZIP_DEFLATED) as zf:
        zf.writestr("cleaned_sales.csv", session["cleaned_csv"])
        zf.writestr("LoadData.m", session["m_script"])
        zf.writestr("dax_measures.dax", session["dax_content"])
        zf.writestr("POWER_BI_MEASURES_CHEATSHEET.md", session["cheatsheet"])
        zf.writestr("audit_log.json", json.dumps(session["audit_log"], indent=2, default=str))
        zf.writestr("README.txt", session["readme"])

    zip_buffer.seek(0)
    download_filename = f"powerbi_pack_{datetime.now().strftime('%Y%m%d_%H%M%S')}.zip"
    return send_file(
        zip_buffer,
        mimetype="application/zip",
        as_attachment=True,
        download_name=download_filename
    )


